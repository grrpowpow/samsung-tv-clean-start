const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.join(__dirname, '..', '.local');
const source = path.join(root, 'baseline.json');
if (!fs.existsSync(source)) throw new Error('Baseline fehlt. Zuerst status ausführen.');
const original = fs.readFileSync(source);
const data = JSON.parse(original);
if (!data.device || !data.device.device || data.device.device.OS !== 'Tizen') throw new Error('Keine gültige Tizen-Baseline.');
const folder = path.join(root, 'recovery', new Date().toISOString().replace(/[:.]/g, '-'));
fs.mkdirSync(folder, {recursive: true});
const copy = path.join(folder, 'baseline.json');
fs.copyFileSync(source, copy, fs.constants.COPYFILE_EXCL);
const hash = value => crypto.createHash('sha256').update(value).digest('hex');
const digest = hash(original);
if (hash(fs.readFileSync(copy)) !== digest) throw new Error('Prüfsummen stimmen nicht überein.');
fs.writeFileSync(path.join(folder, 'SHA256.json'), JSON.stringify({'baseline.json': digest}, null, 2));
console.log('Dateisicherung geprüft: ' + folder);
console.log('Dies bestätigt keine vollständige TV-Sicherung und keinen TV-Rücksetztest.');
